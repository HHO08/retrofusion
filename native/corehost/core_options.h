// Why this exists: the work order requires that core settings are exposed
// through *PPSSPP's own* settings screen and that the defaults are the
// "weak device" (potato) profile tuned per system. Those defaults must exist as
// data, not as scattered ifs, so that:
//   * the settings UI can be generated (native/ppsspp/core_settings_tab.cpp)
//   * the same values feed retro_get_variable() inside the core
//   * a fingerprint can be computed so savestates are never loaded across
//     incompatible option sets
//
// The actual schema comes from cores/core_options.json -> generated by
// tools/gen_cpp_tables.py -> native/corehost/generated/options_data.inc

#pragma once

#include <cstddef>
#include <map>
#include <string>
#include <vector>

namespace rf {

enum class OptionKind {
	kBool,    // stored as "enabled"/"disabled" (libretro convention)
	kEnum,    // exactly one of the declared values
	kInt,     // free integer, clamped to [min_value, max_value]
};

struct OptionChoice {
	const char *label;  // shown in the UI (PPSSPP style, short)
	const char *value;  // value handed to the core
};

struct OptionSpec {
	const char *key;            // libretro variable key
	const char *label;          // UI label
	const char *info;           // one-line description (PPSSPP shows as tooltip)
	OptionKind kind;
	const OptionChoice *choices;
	size_t choice_count;
	const char *default_value;  // "balanced" default
	const char *potato_value;   // weak-device default from the work order
	int min_value;
	int max_value;
	bool restart_core;          // requires core restart to take effect
};

struct CoreOptionSchema {
	const char *core_id;
	const OptionSpec *specs;
	size_t count;
};

const CoreOptionSchema *SchemaForCore(const std::string &core_id);

// All schemas, for validation tooling and for the "Advanced" dump screen.
const CoreOptionSchema *AllSchemas();
size_t AllSchemaCount();

// ---------------------------------------------------------------------------
// Persistence + resolution of effective values.
// Stored in <config>/cores.ini, section [core_id]. Deliberately *not* inside
// ppsspp.ini: PPSSPP rewrites that file on every settings save and we do not
// want to fight its Config system, while still showing everything through
// PPSSPP's UI.
// ---------------------------------------------------------------------------
class CoreOptionsStore {
public:
	bool Load(const std::string &ini_path);
	bool Save() const;

	// Effective value: user value > potato profile > schema default.
	std::string Effective(const std::string &core_id, const OptionSpec &spec) const;
	// Active map handed to CoreHost::SetOptionOverrides().
	std::map<std::string, std::string> EffectiveMap(const std::string &core_id) const;

	void Set(const std::string &core_id, const std::string &key, const std::string &value);
	void ResetToPotato(const std::string &core_id);
	void ResetToBalanced(const std::string &core_id);
	bool IsUserSet(const std::string &core_id, const std::string &key) const;

	// Stable hash of the effective option set: mixed into savestate metadata.
	std::string Fingerprint(const std::string &core_id) const;

private:
	std::string path_;
	// core_id -> (key -> value)
	std::map<std::string, std::map<std::string, std::string> > values_;
};

// Convenience: "enabled"/"disabled" <-> bool, tolerant of "true"/"1".
bool OptionToBool(const std::string &value);
const char *BoolToOption(bool value);

}  // namespace rf
